#ifndef FL_TRAIN_H
#define FL_TRAIN_H
/*
 * fl_train — процедура локального навчання і оцінки.  НАДАЄТЬСЯ.
 *
 * Це те, що виконується на платі у відповідь на команду «навчайся N
 * епох».  Процедура нічого не знає про те, де лежать ваші дані: вона
 * питає їх через колбек.  Саме цей колбек і є вашою частиною роботи.
 *
 * ЩО РЕАЛІЗУЄТЕ ВИ:
 *
 *   1. get_sample() — дістати семпл за індексом зі свого сховища
 *      (розділ флеш-пам'яті) і НОРМАЛІЗУВАТИ ознаки в [0, 1].
 *      Нормалізація — частина контракту даних: хост робить так само.
 *
 *   2. масиви індексів train_idx / val_idx — ваш поділ на тренувальну
 *      і валідаційну частини.  Вони НЕ мають перетинатися (FL-04).
 *
 *   3. виклик fl_train() / fl_eval() з обробника команди протоколу.
 *
 * Приклад підключення — у example_main.c.
 */
#include <stdint.h>

#include "fl_model.h"

typedef struct {
    /* Повертає ознаки семпла `idx` у x[0 .. n_in) та його клас у *y.
     * Ознаки мають бути вже нормалізовані (наприклад, байт / 255). */
    void (*get_sample)(void *ctx, uint32_t idx, float *x, int *y);
    void *ctx;                 /* передається в get_sample без змін */

    /* Індекси тренувальних семплів.  fl_train() перемішує цей масив
     * НА МІСЦІ перед кожною епохою, тому він має бути змінюваним.
     * Порядок усередині тренувальної частини ні на що не впливає. */
    uint16_t *train_idx;
    uint32_t n_train;

    /* Індекси валідаційних семплів; не змінюються. */
    const uint16_t *val_idx;
    uint32_t n_val;
} fl_data_t;

typedef struct {
    uint32_t n;        /* скільки семплів оброблено */
    uint32_t steps;    /* скільки кроків SGD зроблено */
    float loss;        /* середні втрати */
    float acc;         /* частка вгаданих */
} fl_result_t;

/*
 * `epochs` епох SGD по тренувальній частині.
 *
 * Повертає втрати й точність ОСТАННЬОЇ епохи — саме їх звітують
 * серверу як train-метрику.  Кожна епоха перемішує train_idx із
 * seed + номер_епохи, щоб прогін був відтворюваним.
 *
 * batch обрізається до n_train; останній батч епохи може бути неповним,
 * і ділення на його справжній розмір зроблено всередині.
 */
fl_result_t fl_train(fl_model_t *m, fl_data_t *d, int epochs, float lr,
                     int batch, uint32_t seed);

/*
 * Оцінка без зміни вагів.  on_val != 0 — на валідаційній частині,
 * інакше на тренувальній.
 *
 * Серверу звітують саме валідаційне число: точність на тих семплах, на
 * яких щойно вчилися, вимірює запам'ятовування, а не якість моделі.
 */
fl_result_t fl_eval(fl_model_t *m, const fl_data_t *d, int on_val);

/*
 * Обмежує норму оновлення: якщо ||p - global||_2 > max_norm, оновлення
 * масштабується так, щоб норма дорівнювала max_norm.  Повертає
 * застосований коефіцієнт (1.0 — кліпінгу не було).
 * max_norm <= 0 вимикає кліпінг.
 *
 * Потрібно для вимоги FL-11: без обмеженої чутливості оновлення немає
 * жодної гарантії приватності, скільки шуму потім не додавай.
 */
float fl_clip_update(fl_model_t *m, const float *global, float max_norm);

#endif /* FL_TRAIN_H */
