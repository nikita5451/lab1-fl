#ifndef FL_RNG_H
#define FL_RNG_H
/*
 * fl_rng — детермінований генератор випадкових чисел.  НАДАЄТЬСЯ.
 *
 * Використовується при ініціалізації вагів і перемішуванні тренувальної
 * вибірки, тому є частиною контракту моделі: хост і пристрій мають давати
 * побітово однакові послідовності для одного seed.  Дзеркало для Python —
 * у host/fl_model_ref.py.
 *
 * Зміна цього файлу порушує збіг вагів між хостом і пристроєм (FL-03).
 */
#include <stdint.h>

/* splitmix32: перемішує seed.  Потрібне тому, що 0 є нерухомою точкою
 * xorshift32, а seed-и в цій роботі — 0, 1, 2, ... */
uint32_t fl_rng_seed(uint32_t seed);

/* xorshift32 */
uint32_t fl_rng_next(uint32_t *state);

/* Рівномірно на [0, 1), 24 біти мантиси. */
float fl_rng_uniform(uint32_t *state);

/* Перемішування Фішера-Йєтса на місці (згори вниз). */
void fl_rng_shuffle_u16(uint16_t *a, uint32_t n, uint32_t *state);

#endif /* FL_RNG_H */
